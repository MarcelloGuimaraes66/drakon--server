import fs from "node:fs/promises";
import path from "node:path";
import { execFile } from "node:child_process";
import { createRequire } from "node:module";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const desktopRuntimeEnvKeys = [
  "APP_ALLOWED_ORIGINS",
  "R2_PUBLIC_BASE_URL",
  "GOOGLE_OAUTH_CLIENT_ID",
  "GOOGLE_OAUTH_CLIENT_SECRET",
  "DESKTOP_GOOGLE_OAUTH_CLIENT_ID",
  "DESKTOP_GOOGLE_OAUTH_CLIENT_SECRET",
  "DESKTOP_GOOGLE_OAUTH_REDIRECT_URI",
  "GOOGLE_GEOCODING_API_KEY",
  "GEONAMES_USERNAME",
  "CHAT_V2_ENABLED",
  "DAILY_REPORTS",
  "STRIPE_SECRET_KEY",
  "STRIPE_WEBHOOK_SECRET",
  "STRIPE_CHAT_PAYG_PRICE_ID",
  "USD_TO_BRL",
  "SCHEDULER_TICK_SECRET",
  "CENTRAL_AUTH_BASE_URL",
  "CENTRAL_AUTH_GRANT_TTL_HOURS",
  "CENTRAL_AUTH_KEY_ID",
];

function parseArgs(argv) {
  const args = { out: "" };
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (token === "--out" || token === "-o") {
      args.out = argv[index + 1] || "";
      index += 1;
    }
  }
  return args;
}

async function exists(targetPath) {
  try {
    await fs.access(targetPath);
    return true;
  } catch {
    return false;
  }
}

async function readJson(filePath) {
  return JSON.parse(await fs.readFile(filePath, "utf8"));
}

async function copyDir(source, destination) {
  if (!(await exists(source))) {
    throw new Error(`Required runtime package is missing: ${source}`);
  }

  await fs.cp(source, destination, {
    recursive: true,
    force: true,
    verbatimSymlinks: false,
  });
}

async function loadEnvFile(filePath, dotenv) {
  if (!(await exists(filePath))) {
    return {};
  }

  const content = await fs.readFile(filePath, "utf8");
  return dotenv.parse(content);
}

function resolveRuntimeEnvValue(key, sourceEnv) {
  const fromProcess = String(process.env[key] || "").trim();
  if (fromProcess) {
    return fromProcess;
  }

  return String(sourceEnv[key] || "").trim();
}

function resolveRuntimeEnvValueFromAliases(keys, sourceEnv) {
  for (const key of keys) {
    const value = resolveRuntimeEnvValue(key, sourceEnv);
    if (value) {
      return value;
    }
  }

  return "";
}

async function resolveDesktopCentralAuthPublicKey(sourceEnv, drakonSiteRoot) {
  const inlineValue = resolveRuntimeEnvValue("CENTRAL_AUTH_PUBLIC_KEY", sourceEnv);
  if (inlineValue) {
    return inlineValue;
  }

  const configuredPath = resolveRuntimeEnvValue("CENTRAL_AUTH_PUBLIC_KEY_PATH", sourceEnv);
  if (!configuredPath) {
    return "";
  }

  const resolvedPath = path.isAbsolute(configuredPath)
    ? configuredPath
    : path.resolve(drakonSiteRoot, configuredPath);

  if (!(await exists(resolvedPath))) {
    throw new Error(
      `Desktop runtime central auth public key file was not found at ${resolvedPath}`
    );
  }

  return (await fs.readFile(resolvedPath, "utf8")).trim();
}

function serializeEnv(envMap) {
  const header = [
    "# Generated by Perceptrum/linux-desktop/stage-backend-runtime.mjs",
    "# Values here are limited to the Linux desktop runtime bootstrap surface.",
    "",
  ];
  const lines = Object.entries(envMap)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([key, value]) => `${key}=${serializeEnvValue(value)}`);
  return `${header.join("\n")}${lines.join("\n")}\n`;
}

function serializeEnvValue(value) {
  if (value === "") {
    return "";
  }

  if (/[\s#"'`]/.test(value)) {
    return JSON.stringify(value);
  }

  return value;
}

async function stageBrandingMetadata({
  configPath,
  brandSelectorPath,
  runtimeRoot,
  runtimeDrakonSiteRoot,
  activeBrandId,
}) {
  await fs.copyFile(configPath, path.join(runtimeRoot, "brand.config.json"));
  await fs.copyFile(configPath, path.join(runtimeDrakonSiteRoot, "brand.config.json"));

  const selectorTarget = `${activeBrandId}\n`;
  if (await exists(brandSelectorPath)) {
    const selectorContents = await fs.readFile(brandSelectorPath, "utf8");
    await fs.writeFile(path.join(runtimeRoot, "brand.txt"), selectorContents, "utf8");
    await fs.writeFile(
      path.join(runtimeDrakonSiteRoot, "brand.txt"),
      selectorContents,
      "utf8"
    );
    return;
  }

  await fs.writeFile(path.join(runtimeRoot, "brand.txt"), selectorTarget, "utf8");
  await fs.writeFile(path.join(runtimeDrakonSiteRoot, "brand.txt"), selectorTarget, "utf8");
}

async function stageDesktopRuntimeEnv({
  drakonSiteRoot,
  runtimeDrakonSiteRoot,
  dotenv,
}) {
  const initEnvPath = path.join(drakonSiteRoot, ".env.init");
  if (await exists(initEnvPath)) {
    await fs.copyFile(initEnvPath, path.join(runtimeDrakonSiteRoot, ".env.init"));
  }

  const sourceLocalEnv = await loadEnvFile(path.join(drakonSiteRoot, ".env.local"), dotenv);
  const runtimeEnv = {};

  for (const key of desktopRuntimeEnvKeys) {
    const value = resolveRuntimeEnvValue(key, sourceLocalEnv);
    if (value) {
      runtimeEnv[key] = value;
    }
  }

  const dailyReportsValue = resolveRuntimeEnvValueFromAliases(
    ["DAILY_REPORTS", "daily_reports"],
    sourceLocalEnv
  );
  if (dailyReportsValue) {
    runtimeEnv.DAILY_REPORTS = dailyReportsValue;
  }

  const centralAuthPublicKey = await resolveDesktopCentralAuthPublicKey(
    sourceLocalEnv,
    drakonSiteRoot
  );
  const centralAuthBaseUrl = String(runtimeEnv.CENTRAL_AUTH_BASE_URL || "").trim();
  const centralAuthConfigured = Boolean(
    centralAuthBaseUrl ||
      centralAuthPublicKey ||
      resolveRuntimeEnvValue("CENTRAL_AUTH_PUBLIC_KEY_PATH", sourceLocalEnv)
  );

  if (centralAuthConfigured) {
    if (!centralAuthBaseUrl) {
      throw new Error(
        "Desktop runtime central auth is partially configured: CENTRAL_AUTH_BASE_URL is required."
      );
    }
    if (!centralAuthPublicKey) {
      throw new Error(
        "Desktop runtime central auth is partially configured: CENTRAL_AUTH_PUBLIC_KEY or CENTRAL_AUTH_PUBLIC_KEY_PATH is required."
      );
    }

    runtimeEnv.CENTRAL_AUTH_BASE_URL = centralAuthBaseUrl;
    runtimeEnv.CENTRAL_AUTH_PUBLIC_KEY = centralAuthPublicKey;
  }

  await fs.writeFile(
    path.join(runtimeDrakonSiteRoot, ".env.local"),
    serializeEnv(runtimeEnv),
    "utf8"
  );
}

async function writeLauncher(runtimeRoot) {
  const launcherPath = path.join(runtimeRoot, "perceptrum-local-backend.sh");
  await fs.writeFile(
    launcherPath,
    `#!/usr/bin/env sh
set -eu

backend_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
runtime_site_dir="$backend_dir/drakonsite"

if [ -z "\${APP_RUNTIME_ROOT:-}" ]; then
  APP_RUNTIME_ROOT="$backend_dir"
  export APP_RUNTIME_ROOT
fi

if [ -z "\${APP_RUNTIME_ENV:-}" ]; then
  APP_RUNTIME_ENV=local
  export APP_RUNTIME_ENV
fi

if [ -z "\${APP_DB_BACKEND:-}" ]; then
  APP_DB_BACKEND=sqlite
  export APP_DB_BACKEND
fi

if [ -z "\${APP_RUNTIME_CONFIG_ROOT:-}" ]; then
  APP_RUNTIME_CONFIG_ROOT="\${XDG_CONFIG_HOME:-$HOME/.config}/Perceptrum"
  export APP_RUNTIME_CONFIG_ROOT
fi

export NODE_PATH="$backend_dir/node_modules\${NODE_PATH:+:$NODE_PATH}"
cd "$runtime_site_dir"
exec node "$backend_dir/desktop-local-server.cjs" "$@"
`,
    "utf8"
  );
  await fs.chmod(launcherPath, 0o755);
}

async function bundleDesktopLocalBackend({
  appHostRoot,
  drakonSiteRoot,
  runtimeRoot,
  esbuild,
}) {
  await esbuild.build({
    entryPoints: [path.join(appHostRoot, "Runtime", "desktop-local-server.mjs")],
    absWorkingDir: drakonSiteRoot,
    alias: {
      "@": path.join(drakonSiteRoot, "src"),
    },
    bundle: true,
    conditions: ["node", "require", "default"],
    external: ["better-sqlite3-multiple-ciphers"],
    format: "cjs",
    logLevel: "info",
    minify: false,
    nodePaths: [path.join(drakonSiteRoot, "node_modules")],
    outfile: path.join(runtimeRoot, "desktop-local-server.cjs"),
    platform: "node",
    sourcemap: false,
    target: "node22",
  });
}

async function stageDesktopNativeNodePackages({
  drakonSiteRoot,
  nodeModulesRoot,
}) {
  for (const packageName of [
    "better-sqlite3-multiple-ciphers",
    "bindings",
    "file-uri-to-path",
  ]) {
    await copyDir(
      path.join(drakonSiteRoot, "node_modules", ...packageName.split("/")),
      path.join(nodeModulesRoot, ...packageName.split("/"))
    );
  }
}

async function generateDesktopSqliteSeed({
  workspaceRoot,
  drakonSiteRoot,
  bootstrapRoot,
  brandId,
}) {
  const siteStem = `${brandId}_site`;

  await execFileAsync(
    process.execPath,
    [
      path.join(drakonSiteRoot, "scripts", "convert-postgres-dump-to-sqlite.mjs"),
      "--brand",
      brandId,
      "--schema-only",
      "--out",
      path.join(bootstrapRoot, `${siteStem}.seed.sqlite`),
      "--report",
      path.join(bootstrapRoot, `${siteStem}.seed.import-report.json`),
      "--schema-out",
      path.join(bootstrapRoot, `${siteStem}.seed.schema.sql`),
    ],
    {
      cwd: workspaceRoot,
    }
  );
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.out) {
    throw new Error("Usage: node stage-backend-runtime.mjs --out <runtime-dir>");
  }

  const workspaceRoot = path.resolve(import.meta.dirname, "..", "..");
  const appHostRoot = path.join(workspaceRoot, "AppHost");
  const drakonSiteRoot = path.join(workspaceRoot, "DrakonSite");
  const configPath = path.join(workspaceRoot, "brand.config.json");
  const brandSelectorPath = path.join(workspaceRoot, "brand.txt");
  const runtimeRoot = path.resolve(args.out);
  const bootstrapRoot = path.join(runtimeRoot, "bootstrap");
  const nodeModulesRoot = path.join(runtimeRoot, "node_modules");
  const runtimeDrakonSiteRoot = path.join(runtimeRoot, "drakonsite");
  const requireFromDrakonSite = createRequire(path.join(drakonSiteRoot, "package.json"));
  const esbuild = requireFromDrakonSite("esbuild");
  const dotenv = requireFromDrakonSite("dotenv");
  const config = await readJson(configPath);
  const activeBrandId = String(config.activeBrand || "perceptrum").trim().toLowerCase();

  if (!config.brands?.[activeBrandId]) {
    throw new Error(`Active brand "${activeBrandId}" is not defined in brand.config.json`);
  }

  await fs.rm(runtimeRoot, { recursive: true, force: true });
  await fs.mkdir(bootstrapRoot, { recursive: true });
  await fs.mkdir(nodeModulesRoot, { recursive: true });
  await fs.mkdir(runtimeDrakonSiteRoot, { recursive: true });

  await bundleDesktopLocalBackend({
    appHostRoot,
    drakonSiteRoot,
    runtimeRoot,
    esbuild,
  });
  await stageDesktopNativeNodePackages({
    drakonSiteRoot,
    nodeModulesRoot,
  });
  await stageBrandingMetadata({
    configPath,
    brandSelectorPath,
    runtimeRoot,
    runtimeDrakonSiteRoot,
    activeBrandId,
  });
  await stageDesktopRuntimeEnv({
    drakonSiteRoot,
    runtimeDrakonSiteRoot,
    dotenv,
  });

  for (const brandId of ["perceptrum", "drakon"]) {
    if (config.brands?.[brandId]) {
      await generateDesktopSqliteSeed({
        workspaceRoot,
        drakonSiteRoot,
        bootstrapRoot,
        brandId,
      });
    }
  }

  await writeLauncher(runtimeRoot);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.stack || error.message : String(error));
  process.exit(1);
});
